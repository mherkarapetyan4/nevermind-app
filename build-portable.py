"""Rebuild the browser-ready mascot and a standalone, double-clickable HTML copy.

Run with Python 3 after changing the mascot, page, styles, or screenshots.
No third-party build dependencies are required.
"""
import base64
import json
import mimetypes
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT.parents[1] / "output"


def replace_once(text, old, new):
    assert text.count(old) == 1, f"Expected one build marker: {old[:70]}"
    return text.replace(old, new, 1)


three = (ROOT / "assets/three.mjs").read_text()
exports = re.search(r"\nexport \{ ([^}]+) \};\s*$", three)
assert exports, "Three.js must be the checked-in, self-contained module."
three = three[:exports.start()]
assert not re.search(r"^import |^export ", three, re.M)

mascot = (ROOT / "mascot.js").read_text()
names = sorted(set(re.findall(r"THREE\.(\w+)", mascot)))
assert set(names).issubset(set(exports.group(1).split(", ")))
mascot = replace_once(mascot, "import * as THREE from './assets/three.mjs';", "")
metadata = json.loads((ROOT / "assets/mascot-geometry.json").read_text())
mascot = replace_once(mascot, "  const response = await fetch(new URL('./assets/mascot-geometry.json', import.meta.url));\n  if (!response.ok) throw new Error('Mascot unavailable');\n  const data = await response.json();", "  const data = " + json.dumps(metadata) + ";")
mesh = base64.b64encode((ROOT / "assets/mascot.bin").read_bytes()).decode()
mascot = replace_once(mascot, "  const meshResponse = await fetch(new URL('./assets/mascot.bin', import.meta.url));\n  if (!meshResponse.ok) throw new Error('Mascot mesh unavailable');\n  const binary = await meshResponse.arrayBuffer();", "  const binary = Uint8Array.from(atob('" + mesh + "'), char => char.charCodeAt(0)).buffer;")
bundle = "// Generated by build-portable.py. Three.js license: assets/THREE-LICENSE.txt\n(() => {\nconst THREE = (() => {\n" + three + "\nreturn {" + ",".join(names) + "};\n})();\n" + mascot + "\n})();\n"
(ROOT / "assets/mascot.bundle.js").write_text(bundle)

html = (ROOT / "index.html").read_text()
html, count = re.subn(r'<link rel="stylesheet" href="style.css[^" ]*">', lambda _: "<style>" + (ROOT / "style.css").read_text() + "</style>", html)
assert count == 1


def inline_script(match):
    source = (ROOT / match.group(1).split("?")[0]).read_text()
    return "<script>" + source.replace("</script", "<\\/script") + "</script>"


html, count = re.subn(r'<script src="([^"]+)" defer></script>', inline_script, html)
assert count == 2


def inline_image(match):
    attribute, name = match.groups()
    mime = mimetypes.guess_type(name)[0]
    data = base64.b64encode((ROOT / name).read_bytes()).decode()
    return f'{attribute}="data:{mime};base64,{data}"'


html = re.sub(r'(src|href)="((?:screens/|assets/)?[^"/]+\.(?:png|jpg))"', inline_image, html)
OUTPUT.mkdir(exist_ok=True)
(OUTPUT / "nevermind-standalone.html").write_text(html)
print("Built assets/mascot.bundle.js and output/nevermind-standalone.html")
